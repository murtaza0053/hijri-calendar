#!/usr/bin/env python3
"""Regenerates CHANGELOG.md from version.json (web app) and the GitHub releases (Android APK). Run from the repo root after a deploy."""
import json, subprocess, itertools
d = json.load(open('version.json'))
vname = lambda v: v  # the app shows vName(v) in Settings; here we keep the raw build number
out = ["# Changelog", "", "Generated by `tools/make-changelog.py` from `version.json` (web app, newest first) and the GitHub releases (Android APK).", "",
       "Web app build numbers are `APP_V` in `index.html`. The notes are the user-facing English notes shown in the app's \"what's new\" sheet.", "", "## Android APK", ""]
try:
    rel = json.loads(subprocess.check_output(['gh', 'api', 'repos/murtaza0053/hijri-calendar/releases?per_page=50']))
    for i, r in enumerate(x for x in rel if x['tag_name'].startswith('android-')):
        out += [f"### {r['name']} — {r['published_at'][:10]}{' (latest)' if i == 0 else ''}", "", (r.get('body') or '').strip() or "_no notes_", ""]
except Exception as e:
    out += [f"_Could not read GitHub releases: {e}_", ""]
out += ["## Web app", ""]
for date, items in itertools.groupby(d['history'], key=lambda e: e['date']):
    out += [f"### {date}", ""]
    for e in items:
        out += [f"**v{e['v']}**", ""] + [f"- {n}" for n in e.get('en', [])] + [""]
open('CHANGELOG.md', 'w').write("\n".join(out))
print("wrote CHANGELOG.md:", len(d['history']), "web versions")
