CREATE TABLE IF NOT EXISTS subs (
  id TEXT PRIMARY KEY, endpoint TEXT NOT NULL, p256dh TEXT NOT NULL, auth TEXT NOT NULL, prefs TEXT NOT NULL,
  lat REAL NOT NULL, lng REAL NOT NULL, tz TEXT NOT NULL, city TEXT, lang TEXT, created INTEGER, last_tick INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS outbox (
  id INTEGER PRIMARY KEY AUTOINCREMENT, sub_id TEXT NOT NULL, payload TEXT NOT NULL, due INTEGER NOT NULL, tries INTEGER NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS outbox_sub ON outbox(sub_id);
CREATE TABLE IF NOT EXISTS saltimes (loc TEXT NOT NULL, day TEXT NOT NULL, data TEXT NOT NULL, PRIMARY KEY (loc, day));
CREATE TABLE IF NOT EXISTS miqapi (ym TEXT PRIMARY KEY, data TEXT NOT NULL, at INTEGER NOT NULL);
